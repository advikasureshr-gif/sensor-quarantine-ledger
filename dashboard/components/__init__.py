"""Dark navy SOC theme: CSS, KPI cards, status pills. All dynamic text is HTML-escaped before it is injected."""
from __future__ import annotations

import html

import streamlit as st

NAVY, PANEL, BORDER = "#0a1226", "#101b36", "#1e2d52"
CYAN, BLUE, RED, AMBER, GREEN, MUTED, TEXT = "#22d3ee", "#3b82f6", "#ef4444", "#f59e0b", "#2dd4bf", "#8da2c4", "#e6edf7"
DECISION_COLORS = {"TRUSTED": GREEN, "UNCERTAIN": AMBER, "SUSPICIOUS": RED}
TONES = {"cyan": CYAN, "blue": BLUE, "red": RED, "amber": AMBER, "green": GREEN, "muted": MUTED}
PRODUCT = "IoTGuard"
TAGLINE = "Behavioural Anomaly Detection & Attack Simulation Platform"

_CSS = f"""
<style>
html, body, [data-testid="stAppViewContainer"] {{ background: radial-gradient(1200px 600px at 85% -10%, #12224a 0%, {NAVY} 55%); }}
[data-testid="stHeader"] {{ background: transparent; }}
[data-testid="stSidebar"] {{ background: #081022; border-right: 1px solid {BORDER}; }}
.ig-brand {{ font-family: Consolas, "Cascadia Mono", monospace; font-size: 1.35rem; font-weight: 700; color: {CYAN}; letter-spacing: .08em; }}
.ig-tag {{ color: {MUTED}; font-size: .72rem; line-height: 1.3; margin-bottom: .6rem; }}
.ig-card {{ background: linear-gradient(180deg, {PANEL}, #0d1731); border: 1px solid {BORDER}; border-left: 3px solid var(--tone, {CYAN});
            border-radius: 8px; padding: 12px 14px; min-height: 92px; }}
.ig-card .l {{ color: {MUTED}; font-size: .70rem; text-transform: uppercase; letter-spacing: .09em; }}
.ig-card .v {{ font-family: Consolas, "Cascadia Mono", monospace; font-size: 1.6rem; font-weight: 700; color: {TEXT}; line-height: 1.25; }}
.ig-card .s {{ color: {MUTED}; font-size: .74rem; }}
.ig-pill {{ display:inline-block; padding: 2px 10px; border-radius: 999px; font-size: .72rem; font-weight: 700; letter-spacing: .05em;
            border: 1px solid var(--tone); color: var(--tone); background: rgba(255,255,255,.03); }}
.ig-sim {{ border: 1px dashed {AMBER}; color: {AMBER}; border-radius: 6px; padding: 6px 10px; font-size: .78rem; background: rgba(245,158,11,.06); }}
.ig-empty {{ border: 1px dashed {BORDER}; border-radius: 10px; padding: 28px; text-align: center; color: {MUTED}; background: rgba(16,27,54,.5); }}
.ig-note {{ color: {MUTED}; font-size: .78rem; }}
</style>
"""


def inject_css() -> None:
    st.markdown(_CSS, unsafe_allow_html=True)


def sidebar_brand() -> None:
    st.sidebar.markdown(f'<div class="ig-brand">◢ {PRODUCT.upper()}</div><div class="ig-tag">{html.escape(TAGLINE)}</div>', unsafe_allow_html=True)


def page_header(title: str, subtitle: str = "") -> None:
    st.markdown(f"## {title}")
    if subtitle:
        st.markdown(f'<div class="ig-note">{html.escape(subtitle)}</div>', unsafe_allow_html=True)


def kpi(label: str, value, sub: str = "", tone: str = "cyan") -> None:
    c = TONES.get(tone, CYAN)
    st.markdown(f'<div class="ig-card" style="--tone:{c}"><div class="l">{html.escape(str(label))}</div>'
                f'<div class="v">{html.escape(str(value))}</div><div class="s">{html.escape(str(sub))}</div></div>', unsafe_allow_html=True)


def pill(text: str, tone: str = "cyan") -> str:
    return f'<span class="ig-pill" style="--tone:{TONES.get(tone, CYAN)}">{html.escape(str(text))}</span>'


def sim_badge() -> None:
    st.markdown('<div class="ig-sim">⚠ SIMULATED DATA — generated by the IoTGuard simulator. No ESP32 or physical sensor is connected to this dashboard.</div>',
                unsafe_allow_html=True)


def empty_state(title: str, body: str) -> None:
    st.markdown(f'<div class="ig-empty"><b>{html.escape(title)}</b><br>{html.escape(body)}</div>', unsafe_allow_html=True)


def fmt(x, nd: int = 2, dash: str = "—") -> str:
    try:
        return dash if x is None or x != x else f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return dash
